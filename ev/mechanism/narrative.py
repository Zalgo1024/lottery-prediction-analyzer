"""ev/mechanism/narrative —— 叙事解绑的**单一真源**。

（P3，2026-10-03）

——
为什么需要这个模块
——
项目早期是「证伪型」叙事：`ev/`、`prediction/`、`credibility/` 里散落着
「不可预测」「公平随机」「没有任何优势」这类句子。它们有两个问题：

  1. **它们是本体论断言**（世界"不可能"怎样），而本项目能给出的只是
     **认识论结论**（"至今没测到"）。两者混在一句话里，会让后来建成的
     测量能力（`ev/mechanism/` 四轨）在逻辑上被自己的旧文案提前否掉 ——
     「既然已证明不可预测，还测什么缝隙」。
  2. **它们散落在 9 处，措辞各不相同**，改一处漏一处，日后必然再漂移。

本模块把「条件从句」集中成常量，各处引用**同一份文本**。

——
用法：**只追加，不替换**
——
被既有测试锁定的原句必须**逐字保留**，从句追加在其后：

    HONEST_NOTE = (
        "<原句原文，一个字都别改>"
        + RANDOMNESS_PREMISE_CAVEAT
    )

为什么是「追加」而不是「改写」：`tests/test_robust_tiers.py:143`、
`tests/test_coverage.py:137`、`tests/test_threshold.py:64` 分别锁定了原句
里的子串。那些子串是**有价值的诚实边界**（"不提升中奖概率"、
"纪律不下注"），要丢掉的只是「不可能」那层意思，不是边界本身。

——
从句里**刻意不含**当前测量结果
——
不写「当前未检出偏离」。理由与 C 轨 p 地板字段同款（见
`gap_c_structural.structural_bias_report` 的 `口径`）：一旦把时点状态写进
静态文案，数据更新后它就会说谎，而**崩报告比降级更糟**。需要当前状态时
跑 `python cli.py gap`；P5 起由看板自动带出。

——
三个从句的分工
——
  · `RANDOMNESS_PREMISE_CAVEAT` —— 给「概率是组合数常数 / 不改中奖概率」
    这类**以随机开奖为前提**的断言。
  · `NO_SIGNAL_CAVEAT` —— 给「未检出 / 不显著 / 无收益」这类**关于检验
    功效**的断言。
  · `EV_NEGATIVE_CAVEAT` —— 给「EV 恒为负 / 无 edge」这类**按名义返奖率
    算出**的断言。

三者的共同点：把断言的**作用域**显式写出来，并指明该作用域之外由谁负责。
"""

