def payload() -> Dict[str, Any]:
    """`GET /api/ledger/glossary` 的返回体（三键惯例：口径说明 / 诚实边界 / 诚实声明）。"""
    cav = _caveats()
    cards = []
    for c in _CARDS:
        parts = [cav[k] for k in c.get("诚实边界_keys", []) if cav.get(k)]
        extra = c.get("诚实边界补") or ""
        if extra:
            parts.append(extra)
        cards.append({
            "id": c["id"], "序号": c["序号"], "标题": c["标题"],
            "在测什么": c["在测什么"], "名词": list(c["名词"]),
            "口径说明": c["口径说明"],
            "诚实边界": "\n".join(parts),
        })
    return {
        "页码": _PAGE_TITLE,
        "术语": terms(),
        "卡片": cards,
        "主指标": ["净收益率", "最大回撤"],
        "次级指标": ["中奖注数", "中奖期数", "中奖期数_ge10"],
        "口径说明": "金额一律为人民币元；成本按实际注数×单价；奖金按当期规则版本回填；"
                    "税为全额 20%。",
        "诚实边界": cav["未检出"],
        "诚实声明": cav["预计为负"],
    }


