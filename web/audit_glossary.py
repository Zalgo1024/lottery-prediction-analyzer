def card_ids() -> List[str]:
    return [c["id"] for c in _CARDS]


def cards_public() -> List[Dict[str, Any]]:
    """给模板用的卡片骨架：序号 / 标题 / id / key（不含长文案，长文案走 API）。"""
    return [{"id": c["id"], "key": c["key"], "序号": c["序号"], "标题": c["标题"]}
            for c in _CARDS]


def glossary_payload() -> Dict[str, Any]:
    """`GET /api/audit/glossary` 的返回体。

    ★ 三键惯例：`口径说明` / `诚实边界` / `诚实声明`（见 `ev/strategy_stats.py:56-61`）。
    ★ 每张卡的 `诚实边界` = 引用的 narrative 常量 + 本卡的补充说明，**不出现手抄副本**。
    """
    cav = _caveats()
    cmd = cav["测量命令"]

    cards: List[Dict[str, Any]] = []
    for c in _CARDS:
        parts = [cav[k] for k in c.get("诚实边界_keys", []) if cav.get(k)]
        extra = (c.get("诚实边界补") or "").replace("$cmd$", cmd)
        if extra:
            parts.append(extra)
        cards.append({
            "id": c["id"],
            "key": c["key"],
            "序号": c["序号"],
            "标题": c["标题"],
            "在测什么": c["在测什么"],
            "名词": list(c["名词"]),
            "口径说明": c["口径说明"],
            "诚实边界": "\n".join(parts),
        })

    return {
        "术语": terms(),
        "卡片": cards,
        "状态口径": _STATUS_HINT,
        "悬停提示": _HOVER_HINT,
        "页码": _PAGE_术语_TITLE,
        "口径说明": "术语释义按「人话优先」写，精确定义以正文与代码为准；"
                    "每张卡的 `口径说明` 给出取值口径，`诚实边界` 给出结论的作用范围。",
        "诚实边界": cav["未检出"],
        "诚实声明": cav["归因"],
    }


