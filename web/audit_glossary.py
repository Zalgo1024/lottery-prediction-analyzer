def _t(name: str, kind: str, one: str, cal: str = "", scope: Any = None,
       alias: Any = None) -> Dict[str, Any]:
    d = {"名": name, "类": kind, "一句话": one}
    if cal:
        d["口径"] = cal
    d["scope"] = list(scope) if scope else ["*"]
    if alias:
        d["别名"] = list(alias)
    return d


