    back = PR.load()                    # 回读校验：装载不过一例外重要
    print(f"已写 {STORE}")
    print(f"版本 {back['版本']}  哈希 {back['哈希'][:12]}…")
    print(f"Stage1 格 {len(back['格'])} 个；Stage2 方案 {len([k for k in back['格_Stage2']['方案网格'] if k.startswith(('few','inc'))])} 个 + all_single")
