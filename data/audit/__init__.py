"""异常监测与证据留存（与投注模型**物理隔离**）。

这个包存在的唯一理由：把「发现异常」和「改变下注」彻底分开。

★ 两条硬约束，由 `tests/test_audit_no_stake.py` 扫描源码强制：

  1. **不得触发加码**。本包源码中不出现 `apply_dynamic_result` / `record_spend` /
     `clamp` / `resolve_groups`，`checks.py` 也不 import `prediction` 或
     `ev.budget_gate`。异常监测若是能改注数，它就变成了一个「看见不利结果就加注」
     的反馈回路 —— 而那正是所有赌徒破产路径的共同形状。
  2. **不得在开奖后改阈值**。阈值文件带 `锁定: true`，锁定时 `save()` 直接抛错；
     每次检查都记录阈值内容哈希，于是「阈值被改过」本身可查。

关于「开奖可被操控」的立场
--------------------------
本项目只把它当**风险假设**，据此做监测、留证与决策边界，不做任何规避反制的方案，
也不生成所谓必中号。检出异常只是**调查线索**：它不证明操控，更不能用来预测下一期。

且必须明说：公开信息里没有地区级销售组合、没有完整体量结构、没有可审计的开奖前
数据 ⇒ **无法识别地区偏向或具体操控机制**。也不从全国中奖人数倒推号码是如何安排的。
"""

